  /// MaterialApp. This list does not have to be used at all if a custom list
  /// of delegates is preferred or required.
  static const List<LocalizationsDelegate<dynamic>> localizationsDelegates =
      <LocalizationsDelegate<dynamic>>[
        delegate,
        GlobalMaterialLocalizations.delegate,
        GlobalCupertinoLocalizations.delegate,
        GlobalWidgetsLocalizations.delegate,
      ];

  /// A list of this localizations delegate's supported locales.
  static const List<Locale> supportedLocales = <Locale>[
    Locale('de'),
    Locale('en'),
    Locale('fr'),
    Locale('ja'),
  ];

  /// Settings nav label for the General section
  ///
  /// In en, this message translates to:
  /// **'General'**
  String get sectionGeneral;

  /// No description provided for @sectionGeneralSubtitle.
  ///
  /// In en, this message translates to:
  /// **'Language, startup and default model.'**
  String get sectionGeneralSubtitle;

  /// No description provided for @sectionAppearance.
  ///
  /// In en, this message translates to:
  /// **'Appearance'**
  String get sectionAppearance;

  /// No description provided for @sectionAppearanceSubtitle.
  ///
  /// In en, this message translates to:
  /// **'Theme, type scale and accent.'**
  String get sectionAppearanceSubtitle;

  /// No description provided for @sectionEngine.
  ///
  /// In en, this message translates to:
  /// **'Engine & Params'**
  String get sectionEngine;

  /// No description provided for @sectionEngineSubtitle.
  ///
  /// In en, this message translates to:
  /// **'On-device inference via llama.cpp.'**
  String get sectionEngineSubtitle;

  /// No description provided for @sectionPrivacy.
  ///
  /// In en, this message translates to:
  /// **'Privacy & Data'**
  String get sectionPrivacy;

  /// No description provided for @sectionPrivacySubtitle.
  ///
  /// In en, this message translates to:
  /// **'Nothing leaves your device by default.'**
  String get sectionPrivacySubtitle;

  /// No description provided for @sectionStorage.
  ///
  /// In en, this message translates to:
  /// **'Storage'**
  String get sectionStorage;

  /// No description provided for @sectionStorageSubtitle.
  ///
  /// In en, this message translates to:
  /// **'Disk usage and local data.'**
  String get sectionStorageSubtitle;

